#include <iostream>   // подключаем библиотеку для ввода/вывода, без неё — ну никак
#include <cmath>      // математические функции, без sin/cos жизнь боль
#include <iomanip>    // чтобы красиво выводить числа, а не как попало

int main() {
    double alpha_deg, beta_deg; // переменные для углов в градусах
    //std::cout << "Введите alpha (в градусах): "; // просим у юзера альфу
    std::cin >> alpha_deg; // считываем альфу, вдруг введёт 42 — ну и ладно
    //std::cout << "Введите beta (в градусах): ";  // теперь очередь беты
    std::cin >> beta_deg; // снова ждём, пока юзер вспомнит математику

    const double PI = 3.14159265358979323846; // число Пи, и да, оно длинное.
    // да, можно было взять M_PI, но оно не в стандарте. Мы любим боль.

    // переводим углы в радианы, потому что sin/cos в C++ — люди требовательные
    double alpha = alpha_deg * PI / 180.0; // альфа теперь в радианах
    double beta = beta_deg * PI / 180.0; // бета тоже в радианах
    // теперь всё честно. Ну почти.

    // считаем Z1 по формуле из учебника
    // Z1 = 2 * cos((alpha+beta)/2) * sin((alpha-beta)/2) + sin(beta)
    // если забудешь скобки — жди сюрприз 🤡
    double Z1 = 2 * cos((alpha + beta) / 2.0) * sin((alpha - beta) / 2.0) + sin(beta);

    // теперь Z2. По формуле это sqrt(1 - cos^2(alpha)).
    // Что, если подкоренное выражение отрицательное?
    // Ну, математика говорит, что не будет, так что расслабься.
    double Z2 = sqrt(1 - pow(cos(alpha), 2)); // спойлер: это fabs(sin(alpha))

    // выводим результат так, чтобы всё выглядело академически красиво
    std::cout << std::fixed << std::setprecision(6); // 6 знаков после запятой — чисто красота
    std::cout << "\nРезультаты вычислений:\n"; // драматический выход
    std::cout << "Z1 = " << Z1 << "   <-- вот он красавчик\n"; // результат первого монстра
    std::cout << "Z2 = " << Z2 << "   <-- и второй подтянулся\n"; // второй монстр скромнее

    // всё, программа закончилась. Можно идти пить чай ☕️
    return 0; // возвращаем 0, потому что так принято. Если вернуть 42 — комп не поймёт шутки.
}

